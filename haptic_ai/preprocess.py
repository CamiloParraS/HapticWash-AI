"""Preprocessing: resample, bandpass, gravity-align, mirror."""

import pandas as pd


def resample(df: pd.DataFrame) -> pd.DataFrame:
    """Resample time series."""
    return df


def bandpass(df: pd.DataFrame) -> pd.DataFrame:
    """Apply bandpass filter."""
    return df


def gravity_align(df: pd.DataFrame) -> pd.DataFrame:
    """Align to gravity."""
    return df


def mirror(df: pd.DataFrame) -> pd.DataFrame:
    """Mirror/augment samples."""
    return df
